#!/bin/bash
# tests/shell/test_provenance_tools.sh
# Test file checks with small valid, incomplete and mismatched input files.
#
# Usage: bash tests/shell/test_provenance_tools.sh
# Exit: 0 = all tests pass

set -u

SCRIPTDIR=$(cd "$(dirname "$0")/../.." && pwd)
VC="$SCRIPTDIR/tools/verify_chunk.sh"
AP="$SCRIPTDIR/tools/check_dataset_files.sh"
TMP=$(mktemp -d "${TMPDIR:-/tmp}/mmb_provtest.XXXXXX")
trap 'rm -rf "$TMP"' EXIT

pass=0; failed=0
ok()   { pass=$((pass+1)); echo "  PASS: $1"; }
bad()  { failed=$((failed+1)); echo "  FAIL: $1"; }

# expect_pass NAME CMD...
expect_pass() { local name=$1; shift; if "$@" >/dev/null 2>&1; then ok "$name"; else bad "$name (expected pass, got fail)"; fi; }
# expect_fail NAME CMD...
expect_fail() { local name=$1; shift; if "$@" >/dev/null 2>&1; then bad "$name (expected fail, got pass)"; else ok "$name"; fi; }

# Fixture: a well-formed chunk file for dataset_id S, chunk 3 of 7, 5 vertices
make_chunk() {  # make_chunk PATH DATASET_ID CHUNK NCHUNKS NVERTS [WITH_FOOTER]
    local path=$1 dataset_id=$2 chunk=$3 nchunks=$4 nv=$5 footer=${6:-yes}
    {
        echo "% MMB vertices from CUDA kernel"
        echo "% Input: /scratch/runs_output/${dataset_id}/generators_${dataset_id}.txt"
        echo "% Exact MMB color data -- generated by prepareGenerators.m"
        echo "% n=40, tiles_total=3838380, tiles_tested=548340, tiles_intersecting=1000, vertices=${nv}"
        echo "% chunk=${chunk}, nchunks=${nchunks}"
        echo "% gpu_seconds=0.01"
        for i in $(seq 1 "$nv"); do
            echo "4.71028380096${i}e+03 5.5358729405453${i}e+03 1.573381492510${i}e+03"
        done
        if [ "$footer" = yes ]; then
            echo "% complete vertices=${nv}"
        fi
    } > "$path"
}

echo "== verify_chunk.sh =="
S="1931_2deg_D65_A_10nm_refl50"

make_chunk "$TMP/mmb_${S}_chunk3.txt" "$S" 3 7 5 yes
expect_pass "well-formed chunk verifies" bash "$VC" "$TMP/mmb_${S}_chunk3.txt" --require-footer
expect_pass "explicit expectations verify" bash "$VC" "$TMP/mmb_${S}_chunk3.txt" --dataset-id "$S" --chunk 3 --nchunks 7 --require-footer

# Truncation: drop the last data row + footer (kill/quota signature)
make_chunk "$TMP/t.txt" "$S" 3 7 5 yes
head -n 9 "$TMP/t.txt" > "$TMP/mmb_${S}_chunk4.txt"   # header(6) + 3 rows, header says 5
mv "$TMP/mmb_${S}_chunk4.txt" "$TMP/trunc/mmb_${S}_chunk3.txt" 2>/dev/null || {
    mkdir -p "$TMP/trunc"; head -n 9 "$TMP/t.txt" > "$TMP/trunc/mmb_${S}_chunk3.txt"; }
expect_fail "truncated rows rejected (count vs header)" bash "$VC" "$TMP/trunc/mmb_${S}_chunk3.txt"

# Partial trailing line (quota mid-row)
mkdir -p "$TMP/partial"
make_chunk "$TMP/partial/mmb_${S}_chunk3.txt" "$S" 3 7 5 no
printf '%s' "4.7 5.5" >> "$TMP/partial/mmb_${S}_chunk3.txt"  # 6th, malformed row
expect_fail "partial trailing line rejected" bash "$VC" "$TMP/partial/mmb_${S}_chunk3.txt"

# Missing footer under --require-footer
mkdir -p "$TMP/nofoot"
make_chunk "$TMP/nofoot/mmb_${S}_chunk3.txt" "$S" 3 7 5 no
expect_fail "missing footer rejected when required" bash "$VC" "$TMP/nofoot/mmb_${S}_chunk3.txt" --require-footer
expect_pass "missing footer accepted without --require-footer" bash "$VC" "$TMP/nofoot/mmb_${S}_chunk3.txt"

# Wrong provenance: content names a different dataset_id (different illuminants)
mkdir -p "$TMP/alien"
make_chunk "$TMP/alien/mmb_${S}_chunk3.txt" "1931_2deg_D65_LED-B1_1nm_refl50" 3 7 5 yes
expect_fail "wrong-provenance content rejected" bash "$VC" "$TMP/alien/mmb_${S}_chunk3.txt"

# Chunk index mismatch: header says 2, filename says 3
mkdir -p "$TMP/wrongk"
make_chunk "$TMP/wrongk/mmb_${S}_chunk3.txt" "$S" 2 7 5 yes
expect_fail "chunk index mismatch rejected" bash "$VC" "$TMP/wrongk/mmb_${S}_chunk3.txt"

# nchunks mismatch vs expectation
expect_fail "nchunks mismatch rejected" bash "$VC" "$TMP/mmb_${S}_chunk3.txt" --nchunks 9

# NaN row
mkdir -p "$TMP/nan"
make_chunk "$TMP/nan/mmb_${S}_chunk3.txt" "$S" 3 7 4 no
sed -i.bak 's/vertices=4/vertices=5/' "$TMP/nan/mmb_${S}_chunk3.txt" && rm -f "$TMP/nan/"*.bak
echo "nan 5.5e+03 1.5e+03" >> "$TMP/nan/mmb_${S}_chunk3.txt"
expect_fail "NaN row rejected" bash "$VC" "$TMP/nan/mmb_${S}_chunk3.txt"

# Footer/header disagreement
mkdir -p "$TMP/footv"
make_chunk "$TMP/footv/mmb_${S}_chunk3.txt" "$S" 3 7 5 no
echo "% complete vertices=4" >> "$TMP/footv/mmb_${S}_chunk3.txt"
expect_fail "footer/header count disagreement rejected" bash "$VC" "$TMP/footv/mmb_${S}_chunk3.txt"

# Generation identity (--generators): the embedded payload sha must
# match the CURRENT generators file's payload
mkdir -p "$TMP/gen"
{ echo "% cd header"; echo "3"; echo "1.0 2.0 3.0"; echo "400.0 1 1 1 1 1 1"; } > "$TMP/gen/generators_${S}.txt"
if command -v sha256sum >/dev/null 2>&1; then GH="sha256sum"; else GH="shasum -a 256"; fi
GSHA=$(awk '!/^[[:space:]]*%/ && NF>0 {if(n++)printf "\n"; printf "%s",$0}' "$TMP/gen/generators_${S}.txt" | $GH | awk '{print $1}')
{
    echo "% MMB vertices from CUDA kernel"
    echo "% Input: /x/generators_${S}.txt"
    echo "% payload_sha256=${GSHA}"
    echo "% n=40, tiles_total=1, tiles_tested=1, tiles_intersecting=1, vertices=1"
    echo "% chunk=0, nchunks=1"
    echo "1.0 2.0 3.0"
    echo "% complete vertices=1"
} > "$TMP/gen/mmb_${S}_chunk0.txt"
expect_pass "matching generation sha verifies" bash "$VC" "$TMP/gen/mmb_${S}_chunk0.txt" --require-footer --generators "$TMP/gen/generators_${S}.txt"
echo "500.0 9 9 9 9 9 9" >> "$TMP/gen/generators_${S}.txt"   # generators file changed -> new generation
expect_fail "stale-generation chunk rejected" bash "$VC" "$TMP/gen/mmb_${S}_chunk0.txt" --require-footer --generators "$TMP/gen/generators_${S}.txt"
sed '/payload_sha256/d' "$TMP/gen/mmb_${S}_chunk0.txt" > "$TMP/gen/noemb.txt" && mv "$TMP/gen/noemb.txt" "$TMP/gen/mmb_${S}_chunk0.txt"
expect_fail "missing embedded sha rejected when --generators given" bash "$VC" "$TMP/gen/mmb_${S}_chunk0.txt" --require-footer --generators "$TMP/gen/generators_${S}.txt"
expect_pass "no --generators skips the generation check" bash "$VC" "$TMP/gen/mmb_${S}_chunk0.txt" --require-footer

# Staging-named file: verified purely against explicit expectations
mkdir -p "$TMP/stage"
make_chunk "$TMP/stage/.staging.mmb_${S}_chunk3.12345_3.txt" "$S" 3 7 5 yes
expect_pass "staging file verifies with explicit expectations" bash "$VC" "$TMP/stage/.staging.mmb_${S}_chunk3.12345_3.txt" --dataset-id "$S" --chunk 3 --nchunks 7 --require-footer
expect_fail "staging file without --dataset-id rejected" bash "$VC" "$TMP/stage/.staging.mmb_${S}_chunk3.12345_3.txt"
make_chunk "$TMP/stage/.staging.alien.txt" "1931_2deg_D65_LED-B1_1nm_refl50" 3 7 5 yes
expect_fail "staging file with wrong-dataset content rejected" bash "$VC" "$TMP/stage/.staging.alien.txt" --dataset-id "$S" --chunk 3 --nchunks 7 --require-footer

# Single-GPU file (no chunk suffix, no chunk line)
mkdir -p "$TMP/single"
{
    echo "% MMB vertices from CUDA kernel"
    echo "% Input: /x/generators_${S}.txt"
    echo "% n=40, tiles_total=3838380, tiles_tested=3838380, tiles_intersecting=1000, vertices=2"
    echo "% gpu_seconds=0.01"
    echo "1.0e+00 2.0e+00 3.0e+00"
    echo "4.0e+00 5.0e+00 6.0e+00"
    echo "% complete vertices=2"
} > "$TMP/single/mmb_${S}.txt"
expect_pass "single-GPU file verifies" bash "$VC" "$TMP/single/mmb_${S}.txt" --require-footer

echo "== check_dataset_files.sh =="
ROOT="$TMP/runs_output"

mk_summary() {  # mk_summary PATH INPUT_DATASET_ID CHUNK NV
    local path=$1 idsid=$2 chunk=$3 nv=$4
    {
        echo "% MMB vertices from CUDA kernel"
        echo "% Input: /scratch/runs_output/${idsid}/generators_${idsid}.txt"
        echo "% n=401, tiles_total=1, tiles_tested=1, tiles_intersecting=1, vertices=100"
        echo "% chunk=${chunk}, nchunks=49"
        echo ""
        echo "Boundary vertices: ${nv}"
        echo "Boundary faces:    $((2*nv-4))"
        echo "Hull volume:       1.0e+02"
    } > "$path"
}

# Clean dataset_id
A="1931_2deg_D65_A_1nm_refl50"
mkdir -p "$ROOT/$A/results"
mk_summary "$ROOT/$A/results/mmb_${A}_summary.txt" "$A" 0 100
expect_pass "clean collection passes" bash "$AP" --root "$ROOT"

# Wrong-provenance canonical summary
B="1931_2deg_D65_LED-B2_1nm_refl50"
mkdir -p "$ROOT/$B/results"
mk_summary "$ROOT/$B/results/mmb_${B}_summary.txt" "1931_2deg_D65_LED-B1_1nm_refl50" 22 39235
if bash "$AP" --root "$ROOT" | grep -q "INPUT_MISMATCH $B"; then ok "wrong-provenance canonical summary flagged"; else bad "wrong-provenance canonical summary flagged"; fi
if bash "$AP" --root "$ROOT" | grep -q "PARTIAL_HEADER $B"; then ok "partial-set header flagged"; else bad "partial-set header flagged"; fi

# A file named for another dataset in the results directory
C="1931_2deg_D65_LED-B3_1nm_refl50"
mkdir -p "$ROOT/$C/results"
mk_summary "$ROOT/$C/results/mmb_${C}_summary.txt" "$C" 0 100
mk_summary "$ROOT/$C/results/mmb_1931_2deg_D65_LED-B4_1nm_refl50_summary.txt" "1931_2deg_D65_LED-B4_1nm_refl50" 22 41191
if bash "$AP" --root "$ROOT" | grep -q "ALIEN_FILE $C"; then ok "file from another dataset flagged"; else bad "file from another dataset flagged"; fi

# Count mismatch between summary and CSV
D="cfb_2deg_D65_A_1nm_refl50"
mkdir -p "$ROOT/$D/results"
mk_summary "$ROOT/$D/results/mmb_${D}_summary.txt" "$D" 0 3
printf '1 2 3\n4 5 6\n' > "$ROOT/$D/results/mmb_${D}_vertices.csv"
if bash "$AP" --root "$ROOT" | grep -q "COUNT_MISMATCH $D"; then ok "summary/CSV count mismatch flagged"; else bad "summary/CSV count mismatch flagged"; fi

# Missing summary: flagged by default, tolerated with --allow-missing
E="lms_2deg_D65_A_1nm_refl50"
mkdir -p "$ROOT/$E/results"
if bash "$AP" --root "$ROOT" | grep -q "MISSING_SUMMARY $E"; then ok "missing summary flagged"; else bad "missing summary flagged"; fi
if bash "$AP" --root "$ROOT" --allow-missing | grep -q "MISSING_SUMMARY $E"; then bad "allow-missing suppresses"; else ok "allow-missing suppresses"; fi

expect_fail "collection with violations exits nonzero" bash "$AP" --root "$ROOT"

echo ""
echo "provenance tools: $pass passed, $failed failed"
[ "$failed" -eq 0 ]
